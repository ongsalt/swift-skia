#!/usr/bin/env python3
"""Stages Skia's public headers for the artifact bundle, under a `skia/` namespace.

Skia's headers include each other from the repository root (`#include "include/core/SkTypes.h"`),
which would force dependents' header search path to expose a bare `include/`. Instead the headers
are copied under `skia/` and those includes are rewritten relative to the including file, so
dependents only ever see `skia/…`:

    #include "skia/include/c/sk_image.h"           // the C API (what Swift imports)
    #include "skia/include/core/SkCanvas.h"        // the C++ API, for C++ glue code

`skia/include/config/SkUserConfig.h`, which every Skia header loads, gets the library's public
defines, so C++ compiled against these headers matches the prebuilt library's layouts.

usage: stage_headers.py <skia-src> <dest> [-D NAME[=VALUE]]...
       -> <dest>/skia/include/…, <dest>/skia/modules/skcms/…
"""
import argparse
import os
import pathlib
import re
import shutil

# Besides include/: the parts of the tree public headers include.
EXTRA = ["modules/skcms/skcms.h", "modules/skcms/src/skcms_public.h"]
HEADER_SUFFIXES = {".h", ".hpp", ".inc"}
ROOTED_INCLUDE = re.compile(r'(#\s*include\s+")((?:include|modules)/[^"]+)(")')


def stage(src: pathlib.Path, dest: pathlib.Path, defines: list[str]) -> None:
    root = dest / "skia"
    shutil.rmtree(root, ignore_errors=True)
    files = [p.relative_to(src) for p in (src / "include").rglob("*") if p.suffix in HEADER_SUFFIXES]
    files += [pathlib.Path(p) for p in EXTRA]
    for rel in files:
        (root / rel).parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(src / rel, root / rel)

    unresolved = set()
    for rel in files:
        path = root / rel

        def relative(m: re.Match) -> str:
            target = root / m.group(2)
            if not target.exists():
                unresolved.add(m.group(2))
                return m.group(0)
            return m.group(1) + os.path.relpath(target, path.parent).replace(os.sep, "/") + m.group(3)

        text = path.read_text(encoding="utf-8", errors="surrogateescape")
        new = ROOTED_INCLUDE.sub(relative, text)
        if new != text:
            path.write_text(new, encoding="utf-8", errors="surrogateescape")

    config = root / "include" / "config" / "SkUserConfig.h"
    lines = ["// Generated by native/stage_headers.py: the public defines libSkiaSharp was built with.",
             "#ifndef SkUserConfig_DEFINED", "#define SkUserConfig_DEFINED", ""]
    for d in defines:
        name, _, value = d.partition("=")
        lines += [f"#ifndef {name}", f"#define {name} {value}".rstrip(), "#endif"]
    lines += ["", "#endif"]
    config.write_text("\n".join(lines) + "\n")

    print(f"staged {len(files)} headers under {root}")
    if unresolved:
        # Only headers for parts we don't ship (e.g. Dawn, Metal); including those fails loudly.
        print(f"left {len(unresolved)} includes rooted (targets not shipped), e.g. {sorted(unresolved)[:3]}")


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("src", type=pathlib.Path)
    ap.add_argument("dest", type=pathlib.Path)
    ap.add_argument("-D", dest="defines", action="append", default=[])
    args = ap.parse_args()
    stage(args.src, args.dest, args.defines)


if __name__ == "__main__":
    main()
